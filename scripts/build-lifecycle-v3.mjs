import { readFile, writeFile } from 'node:fs/promises';
import { STEPS } from '../emails/lifecycle/v3/schedule.mjs';

const assets = new URL('../emails/lifecycle/v3/', import.meta.url);
const templates = {};
for (const { step, stem, subject } of STEPS) {
  templates[step] = {};
  for (const variant of ['free', 'pro']) {
    const [html, text] = await Promise.all(['html', 'txt'].map(
      extension => readFile(new URL(`${stem}.${variant}.${extension}`, assets), 'utf8')
    ));
    templates[step][variant] = { subject, html, text };
  }
}

const output = new URL('../src/lifecycle-v3-templates.js', import.meta.url);
const content = '// Generated by scripts/build-lifecycle-v3.mjs from the approved HTML and text assets.\n'
  + `export const templates = ${JSON.stringify(templates, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== content) throw new Error('Lifecycle v3 assets are out of date');
} else {
  await writeFile(output, content);
}
